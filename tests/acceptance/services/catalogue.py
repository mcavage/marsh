@dataclasses.dataclass(frozen=True)
class Break:
    mode: str
    check: str  # c1.. or "perf"
    kind: str = "marsh"
    variant: str | None = None
    prerequisites: tuple[str, ...] = ()


@dataclasses.dataclass(frozen=True)
class Entry:
    id: str
    title: str
    tier: str  # smoke | full | perf | soak | release
    owner: str = ""
    est: int = 0  # minutes
    smoke: bool = False
    runner: str = "marsh"  # marsh: services_uat.py; narwhal: Swift journey tests
    breaks: tuple[Break, ...] = ()


def B(mode: str, check: str, kind: str = "marsh", variant: str | None = None,
      *prerequisites: str) -> Break:
    return Break(mode, check, kind, variant, prerequisites)


