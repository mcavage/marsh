"""The scenario catalogue of the services test plan (TEST-PLAN §C, revision 2): every ID, its tier,
owner and estimate, and the defect modes that must make it fail at one named check (§A.6).

A `Break` is one cell `(scenario, variant, mode)`: the mode, the single check the scenario must fail at,
the holds/faults it needs in passes 2 and 3 (prerequisites), and its kind:

- `marsh`: a `MARSH_TEST_BREAK` mode on a `test-breaks` install (daemon env, forwarded to the worker/agent);
- `narwhal`: a `NARWHAL_TEST_BREAK` mode, verified by Narwhal's Swift runner;
- `harness`, `fixture`, `patch`: a change to this harness, a fixture, or a patch file (`sdlc/break/*.patch`);
- `positive-control`: not a defect (`demo`): the scenario itself checks it.

The prerequisites default to every hold/fault the scenario's text names; PREREQUISITE_OVERRIDES narrows
cells where two holds cannot be on together. Scenarios stay `pending` until a task implements them
(`IMPLEMENTED` in services_uat.py), so `--list` is complete from day one. Regenerate from the plan, do not edit
rows by hand: `services_uat.py --list-breaks` must reproduce the plan's §A.6 table.
"""

